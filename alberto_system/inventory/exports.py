def apply_standard_word_style(document, landscape=False):
    """Applies standard page setup and margins."""
    section = document.sections[0]
    if landscape:
        section.orientation = WD_ORIENT.LANDSCAPE
        section.page_width = Inches(11)
        section.page_height = Inches(8.5)
    else:
        section.orientation = WD_ORIENT.PORTRAIT
        section.page_width = Inches(8.5)
        section.page_height = Inches(11)

    # Increased margins to 0.5 to prevent edge cut-offs on different printers
    section.left_margin = Inches(0.5)
    section.right_margin = Inches(0.5)
    section.top_margin = Inches(0.5)
    section.bottom_margin = Inches(0.5)


def set_cell_background(cell, color_hex):
    """Helper to set background color of a Word table cell."""
    shading_elm = parse_xml(r'<w:shd {} w:fill="{}"/>'.format(nsdecls('w'), color_hex))
    cell._tc.get_or_add_tcPr().append(shading_elm)

def add_excel_logo(ws):
    """Adds the company logo to the top-left of the worksheet."""
    logo_path = os.path.join(settings.BASE_DIR, 'static', 'images', 'logo.png')
    if os.path.exists(logo_path):
        img = Image(logo_path)
        img.width = 60
        img.height = 60
        ws.add_image(img, 'A1')

def create_header(document, title, subtitle_lines=[], width_inches=7.2):
    """Creates a professional header with Company Name and Report Details."""
    table = document.add_table(rows=1, cols=2)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = False
    table.allow_autofit = False
    table.columns[0].width = Inches(width_inches / 2)
    table.columns[1].width = Inches(width_inches / 2)
    
    # Left: Company Name
    cell_left = table.cell(0, 0)
    p = cell_left.paragraphs[0]
    
    # Logo
    logo_path = os.path.join(settings.BASE_DIR, 'static', 'images', 'logo.png')
    if os.path.exists(logo_path):
        run_logo = p.add_run()
        run_logo.add_picture(logo_path, width=Inches(0.6))
        p.add_run("  ")

    run = p.add_run("Alberto Grocers")
    run.bold = True
    run.font.name = 'Arial'
    run.font.size = Pt(22)
    run.font.color.rgb = RGBColor(0x2C, 0x3E, 0x50)
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    
    # Right: Report Info
    cell_right = table.cell(0, 1)
    p = cell_right.paragraphs[0]
    run = p.add_run(title)
    run.bold = True
    run.font.name = 'Arial'
    run.font.size = Pt(18)
    run.font.color.rgb = RGBColor(0x27, 0x99, 0xA5)
    p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    
    for line in subtitle_lines:
        p2 = cell_right.add_paragraph()
        p2.alignment = WD_ALIGN_PARAGRAPH.RIGHT
        run2 = p2.add_run(line)
        run2.bold = True 
        run2.font.name = 'Arial'
        run2.font.size = Pt(10)
        run2.font.color.rgb = RGBColor(0x7F, 0x8C, 0x8D)
    
    document.add_paragraph() # Spacer

    # Add a horizontal line
    p = document.add_paragraph()
    p.paragraph_format.space_before = Pt(0)
    p.paragraph_format.space_after = Pt(10)
    pPr = p._element.get_or_add_pPr()
    pBdr = parse_xml(r'<w:pBdr {}><w:bottom w:val="single" w:sz="6" w:space="1" w:color="auto"/></w:pBdr>'.format(nsdecls('w')))
    pPr.append(pBdr)

def style_table_header(row, headers):
    """Styles the header row of a table."""
    for i, text in enumerate(headers):
        cell = row.cells[i]
        cell.vertical_alignment = WD_ALIGN_VERTICAL.CENTER
        set_cell_background(cell, "2C3E50")
        cell.text = ""
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        run = p.add_run(text)
        run.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
        run.font.name = 'Arial'
        run.bold = True
        run.font.size = Pt(11)
        
        # Add padding
        p.paragraph_format.space_before = Pt(4)
        p.paragraph_format.space_after = Pt(4)

def add_word_footer(document):
    """Adds a standard footer to the bottom of the Word document."""
    document.add_paragraph()
    footer_p = document.add_paragraph()
    footer_p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    footer_run = footer_p.add_run(f"Generated by Alberto Inventory POS on {timezone.now().strftime('%B %d, %Y %I:%M %p')}")
    footer_run.font.name = 'Arial'
    footer_run.font.size = Pt(8)
    footer_run.italic = True
    footer_run.font.color.rgb = RGBColor(0x95, 0xA5, 0xA6)

